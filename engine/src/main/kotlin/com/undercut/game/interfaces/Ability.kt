    companion object {
        val byStructId = entries.associateBy { it.structId }
        val byCooldownVarc = entries.associateBy { it.varcEndCd }

        private val UTILITY_CS2_VARCS = setOf(2092, 3736, 3733, 4098, 1)

        fun debugCooldownVarc(varc: Varc) {
            if (varc.newValue <= Bootstrap.client.clientCycle+10) return
            if (varc.newValue >= Bootstrap.client.clientCycle+16000) return
            if (UTILITY_CS2_VARCS.contains(varc.id)) return //GCD and other debug ones
            val ability = byCooldownVarc[varc.id] ?: return println("Possible unidentified cooldown varc: ${varc.id}")
            println("[AbilityCooldown]: ${ability.properName} -> ${format(ability.cooldownTicks)} ticks (${format(ability.cooldownTicks * 600.0 / 1000.0)} secs)")
        }
    }

    fun getStructParam(paramId: Int) = Cache.struct(structId)?.getIntValue(paramId, 0) ?: 0
    fun isSecondaryGlobalCDType() = getStructParam(ABILITY_SECONDARY_GLOBAL_COOLDOWN_PARAM) == 1

    val cooldownTicks: Double
        get() {
            if (isSecondaryGlobalCDType()) return if (varcs.getVar(2216) > Bootstrap.client.clientCycle) (varcs.getVar(2216).toDouble() - Bootstrap.client.clientCycle) / 30.0 else 0.0
            if (varcEndCd == -1) return 0.0
            if (varcs.getVar(varcEndCd) > Bootstrap.client.clientCycle) return (varcs.getVar(varcEndCd).toDouble() - Bootstrap.client.clientCycle) / 30.0
            return if (varcs.getVar(2092) > Bootstrap.client.clientCycle) ((varcs.getVar(2092).toDouble() - Bootstrap.client.clientCycle) / 30.0) else 0.0
        }

    val cooldownMs: Long
        get() = cooldownTicks.toLong() * 600L

    val cooldownTicksIgnoreGCD: Double
        get() {
            if (isSecondaryGlobalCDType()) return if (varcs.getVar(2216) > Bootstrap.client.clientCycle) (varcs.getVar(2216).toDouble() - Bootstrap.client.clientCycle) / 30.0 else 0.0
            if (varcEndCd == -1) return 0.0
            if (varcs.getVar(varcEndCd) > Bootstrap.client.clientCycle) return (varcs.getVar(varcEndCd).toDouble() - Bootstrap.client.clientCycle) / 30.0
            return 0.0
        }

    val cooldownMsIgnoreGCD: Long
        get() = cooldownTicksIgnoreGCD.toLong() * 600L

    val offCd get() = cooldownTicks <= 0.6
    val offCdIgnoreGCD get() = cooldownTicksIgnoreGCD <= 0.6
